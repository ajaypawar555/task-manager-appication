-- Run this migration in the Supabase SQL Editor. It is safe to apply once to a new project.
create table if not exists public.tasks (
    id bigint generated by default as identity primary key,
    title text not null check (char_length(btrim(title)) between 1 and 200),
    description text check (description is null or char_length(description) <= 5000),
    status text not null default 'pending' check (status in ('pending', 'in_progress', 'completed')),
    priority text not null default 'medium' check (priority in ('low', 'medium', 'high')),
    due_date timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create extension if not exists pg_trgm;

create index if not exists idx_tasks_status on public.tasks (status);
create index if not exists idx_tasks_priority on public.tasks (priority);
create index if not exists idx_tasks_created_at on public.tasks (created_at desc);
create index if not exists idx_tasks_due_date on public.tasks (due_date) where due_date is not null;
create index if not exists idx_tasks_title_search on public.tasks using gin (title gin_trgm_ops);

create or replace function public.set_tasks_updated_at()
returns trigger
language plpgsql
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists set_tasks_updated_at on public.tasks;
create trigger set_tasks_updated_at
before update on public.tasks
for each row execute function public.set_tasks_updated_at();

-- Enable RLS and keep anonymous/authenticated roles from reading or changing data.
-- The initial trusted backend uses a server-only Supabase secret key plus its own API token.
alter table public.tasks enable row level security;
revoke all on table public.tasks from anon, authenticated;
grant all on table public.tasks to service_role;
grant usage, select on sequence public.tasks_id_seq to service_role;
